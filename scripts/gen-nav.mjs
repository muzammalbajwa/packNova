#!/usr/bin/env node
// Writes src/content/navData.ts: the header menu and the product list as plain data, taken from the catalog.
// The header and the quote form import navData instead of the catalog, so the 31 pages of copy (about 15 kB gzip)
// are not downloaded on every page. Runs before every build (npm "prebuild"); commit the result.
import { register } from "node:module";
import { writeFileSync } from "node:fs";
register("./lib/ts-loader.mjs", import.meta.url);
const { NAV, GROUPS, PAGES, HOME_CATEGORY_HREF } = await import("../src/content/catalog.ts");
const out = `/* GENERATED by scripts/gen-nav.mjs from src/content/catalog.ts. Do not edit: change the catalog and run npm run build. */
import type { RecipeId } from "./catalog";
export { ROUTES, quoteHref } from "./routes";

export interface NavItem {
  label: string;
  href?: string;
  group?: string;
  items?: { label: string; href: string; recipe: RecipeId }[];
}

export const NAV: NavItem[] = ${JSON.stringify(NAV)};

export const GROUPS_MIN: { id: string; label: string; href: string }[] = ${JSON.stringify(GROUPS.map((g) => ({ id: g.id, label: g.label, href: g.href })))};

/** Page titles by group, for the product list of the quote form. */
export const PRODUCT_TITLES: { group: string; titles: string[] }[] = ${JSON.stringify(GROUPS.map((g) => ({ group: g.label, titles: PAGES.filter((p) => p.group === g.id).map((p) => p.title) })))};

export const HOME_CATEGORY_HREF: Record<string, string> = ${JSON.stringify(HOME_CATEGORY_HREF)};
`;
writeFileSync(new URL("../src/content/navData.ts", import.meta.url), out);
console.log(`navData.ts: ${NAV.length} menu entries, ${PAGES.length} pages`);
